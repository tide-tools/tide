#!/usr/bin/env python3
"""Синтетическая работа для замера «доживает ли работа до пятого шва».

Ставит с нуля изолированный дом tide, проект и нить с одной работой на семь
пунктов — так, чтобы её нельзя было сделать за один подход, и чтобы в ней было
что терять на швах:

  · три вопроса, на которые нет ответа заранее — сессия обязана решить их
    сама и записать решением;
  · один заранее отвергнутый вариант, который нельзя предлагать снова;
  · одна находка, посаженная в материал: её видно на первом пункте, а нужна
    она на шестом — то есть она обязана пережить четыре передачи.

Ничего не трогает за пределами своей папки: свой дом, свой проект,
свой ростер. Рабочие проекты и нити не задействованы.

    python3 bench/five_sessions/fixture.py /path/to/run-dir

Печатает путь к проекту, слаг нити и номер работы.
"""

import os
import subprocess
import sys
from pathlib import Path

# Фикстура лежит В движке: bench/five_sessions/fixture.py → корень → src
ENGINE_SRC = str(Path(__file__).resolve().parents[2] / "src")

# ── материал: тексты, которые сторож будет проверять ──────────────────────────
# Нарушения посажены нарочно. NOTES.md несёт находку: ссылку на README.md,
# который tide перегенерирует из канона, — чинить его бесполезно, он вернётся.
# Про перегенерацию нигде не написано: это надо заметить и донести до пункта 6.

TEXTS = {
    "docs/pravila.md": """# Правила текстов

Строки держим короткими.  Здесь нарочно два пробела.

Вот очень длинная строка, которая тянется и тянется без всякой нужды, потому что автор не остановился вовремя и всё писал и писал.

Ссылка на [заметки](NOTES.md) — живая.
Ссылка на [пропавший файл](docs/net-takogo.md) — мёртвая.
""",
    "docs/NOTES.md": """# Заметки

Короткие строки.

Ссылка на [корневой README](../README.md) — он собран не руками.

Ещё одна строка,  с двойным пробелом.
""",
    "docs/slovar.md": """# Словарь

термин — объяснение
ещё термин — ещё объяснение

Эта строка тоже длиннее ста символов, и она здесь ровно затем, чтобы правило про длину поймало не один файл, а два.
""",
}

WORK_TITLE = ("Сторож стиля: проверка текстов одной командой, "
              "правила принимаются по ходу")

WORK_ITEMS = [
    "Каркас: `guard.py` гоняется одной командой, сам находит тексты проекта, "
    "печатает отчёт и возвращает ненулевой код, если нашёл нарушения",
    "Правило «длинная строка»: порог живёт в одном месте в коде. "
    "ОТКРЫТЫЙ ВОПРОС: порог 80 или 100 — решить и записать решением",
    "Правило «двойной пробел»: два и более пробела подряд внутри строки",
    "Правило «мёртвая ссылка»: markdown-ссылка на файл, которого нет. "
    "ОТКРЫТЫЙ ВОПРОС: ссылки на http проверять или пропускать — решить и "
    "записать решением",
    "Отчёт читаемый: сгруппирован по файлам, у каждой строки адрес "
    "`файл:строка`, в конце итог одной строкой. ОТКРЫТЫЙ ВОПРОС: текст или "
    "json — решить и записать решением",
    "Список исключений: то, что решено не чинить, лежит файлом и сторож на "
    "это не ругается",
    "Самопроверка: сторож гоняется по текстам проекта и проходит чисто",
]

PLAN = """# план нити storozh · v1

final: в проекте есть сторож стиля — одна команда проверяет тексты по
принятым правилам, отчёт читается глазами, и то, что решено не чинить,
сторож молча пропускает.

Рамка: работа ведётся ПОДХОДАМИ. За один подход берётся один-два пункта,
после чего сессия передаёт работу следующей. Это не про размер задачи —
это про то, как здесь принято работать.

## шаги

- [ ] 1. сторож работает | каркас, три правила, читаемый отчёт, исключения,
  самопроверка | результат: «одна команда — и я вижу, что не так с текстами»

## текущий шаг — 1 (сторож работает)

Что делается: работа 01 «Сторож стиля», семь пунктов, ведётся подходами.
Три вопроса внутри неё не решены заранее — их решает та сессия, которая до
них дошла, и записывает решением (`tide decision add`).

## патчи

- v1 — план рождён вместе с нитью.
"""

DECISION_REJECTED = dict(
    what="Сторож живёт на стандартной библиотеке: внешних зависимостей нет",
    why=("Проект получают люди, у которых нет ничего, кроме питона. "
         "Внешний движок регулярок или линтер-фреймворк добавляет установку "
         "до первого запуска, а сторож должен запускаться сразу после clone. "
         "Проверено: всё, что нужно, есть в re, pathlib и argparse"),
    closes=("спор «взять готовый линтер / внешнюю библиотеку регулярок / "
            "своими руками на стдлибе» — не перерешивать: стдлиб"),
)


def sh(args, cwd, env, check=True):
    r = subprocess.run(args, cwd=str(cwd), env=env, capture_output=True, text=True)
    if check and r.returncode != 0:
        sys.stderr.write("FAILED: {0}\n{1}\n{2}\n".format(args, r.stdout, r.stderr))
        sys.exit(1)
    return r.stdout


def build(run_dir: Path):
    home = run_dir / "home"
    proj = run_dir / "lint-guard"
    home.mkdir(parents=True, exist_ok=True)
    proj.mkdir(parents=True, exist_ok=True)

    env = dict(os.environ, TIDE_HOME=str(home))

    sh(["tide", "init", "--name", "bench-home"], home, env)
    sh(["tide", "adopt", "--name", "lint-guard", "--no-orca", "--goal",
        "маленький сторож стиля: проверяет тексты проекта по правилам, "
        "которые команда принимает по ходу"], proj, env)

    for rel, body in TEXTS.items():
        p = proj / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body, encoding="utf-8")

    # нить — тем же вызовом, которым её рождает `tide spark`
    # (у spark --dry-run нить НЕ рождается намеренно, cand 98)
    sys.path.insert(0, ENGINE_SRC)
    from tide.arc import stream  # noqa: E402
    stream.new_thread(proj, "storozh",
                      goal="сторож стиля работает: правила приняты, проверка "
                           "гоняется одной командой, отчёт читаемый")

    thread = next(d for d in (proj / ".tide/arcs").iterdir()
                  if d.name.endswith("@storozh"))
    (thread / "plan.md").write_text(PLAN, encoding="utf-8")

    sh(["tide", "decision", "add", DECISION_REJECTED["what"],
        "--thread", "storozh",
        "--why", DECISION_REJECTED["why"],
        "--closes", DECISION_REJECTED["closes"]], proj, env)

    sh(["tide", "work", "add", WORK_TITLE], proj, env)
    num = sh(["tide", "work", "list"], proj, env).split()[0].split("-")[0]
    sh(["tide", "work", "thread", num, "--set", thread.name], proj, env, check=False)
    for it in WORK_ITEMS:
        sh(["tide", "work", "propose", num, it], proj, env)
    sh(["tide", "work", "agree", num, "--all", "--word",
        "план согласован: гоу, ведём подходами"], proj, env, check=False)

    # первая сессия — есть куда сесть
    stream.new_session(proj, thread.name, "start",
                       goal="сторож стиля: первый подход по работе 01")

    return proj, thread.name, num


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    p, t, n = build(Path(sys.argv[1]).resolve())
    print("project:", p)
    print("thread: ", t)
    print("work:   ", n)
