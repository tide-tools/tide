"""tide.arc.dialog — слова человека в нити и хвост журнала для автохендоффа.

Два журнала, у каждого свой писатель:

* ``<нить>/dialog.md`` — слова Гриши, сказанные в любой сессии нити (решение 13:
  «любая реплика владельца без потерь, только его слова»). Пишет tide —
  UserPromptSubmit-хук ``handoff-confirm`` через :func:`log_human`. Служебные
  вставки (task-notification, межсессионная почта, ``[watch]``, посев AO…) —
  не слова человека, их отсекает :func:`human_text`. Сбой записи — сигнал
  (stderr, ``.tide/state/dialog-errors.log``, ``$TIDE_ALERT_CMD``), не тишина.
* журнал пульта (``dialog.jsonl``, обе стороны Telegram/Linear) — его ведёт
  пульт; tide только читает хвост (:func:`tail`), чтобы новая сессия
  (:mod:`tide.launcher.autohandoff`) знала, о чём говорили последним.

Где журнал — настраивается, без привязки к конкретному проекту:

1. ``$TIDE_DIALOG_LOG`` — путь к файлу;
2. поле ``dialog-log:`` в паспорте нити (абсолютный путь или от корня проекта).

Нет ни того, ни другого, или файла нет — хвоста нет, и это не ошибка.

Форматы: ``.jsonl`` (``{"ts", "dir": "in"|"out", "kind", "text"}`` — как у
пульта) рендерится строкой на реплику, ответ обрезан до :data:`CLIP`; любой
другой файл (например ``dialog-tail.md``) отдаётся последними непустыми строками.
"""

from __future__ import annotations

import json
import os
import re
import shlex
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from typing import List, Optional, Tuple

from .. import fields, paths, slug

LOG_ENV = "TIDE_DIALOG_LOG"
LOG_FIELD = "dialog-log"

HUMAN = "Гриша"
AGENT = "агент"

# Реплика бывает простынёй — посеву нужна суть, полный текст живёт в журнале.
CLIP = 500

# Журнал растёт; хвост всегда у конца файла.
_TAIL_BYTES = 256 * 1024

DIALOG_FILENAME = "dialog.md"
HEADER = "# диалог нити\n\nСтрока на реплику: время · кто · канал · текст. Пишут хуки tide.\n\n"
ERRORS_LOG = "dialog-errors.log"
ALERT_CMD_ENV = "TIDE_ALERT_CMD"

CH_AO = "ao"
CH_TG = "tg"

_LINE_RE = re.compile(r"^- (\S+) · ([^·]+?) · (\S+) · (.*)$")
# Одна реплика в двух журналах: время у пульта и у хука расходится на секунды.
DUP_WINDOW = 600

_TG_RE = re.compile(r"^\s*\[tg\]\s*", re.IGNORECASE)
# Промпт, который начинается так, — не слово человека: его вставил харнесс
# (уведомление задачи, межсессионная почта, слеш-команда), пульт (сводка
# ``[watch]``, сигнал, пересказ Linear — его пишет сам пульт в dialog.jsonl) или
# tide (посев сессии в AO, служебный чат SDK).
_INJECTED_PREFIXES = (
    "<task-notification", "<cross-session-message", "<teammate-message",
    "<system-reminder", "<command-name>", "<command-message>", "<local-command-",
    "<user-prompt-submit-hook", "<ao-session-delivery", "[watch]", "[alert", "[linear ",
    "Ты запущен tide через Agent Orchestrator", "Summarize this agent result",
    "Caveat: The messages below were generated by the user while running local commands",
    # уведомления харнесса, которые приходят промптом «от пользователя» (SOC-101 F17:
    # «usage limit has reset» лёг в сид неотвеченной репликой Гриши)
    "[Cross-session", "[SYSTEM NOTIFICATION", "Your claude.ai usage limit",
    # межсессионная почта uds приходит с шапкой харнесса перед тегом (SOC-101 F47)
    "Another Claude session sent a message",
)
# «usage limit has reset» бывает и без «Your claude.ai» в начале.
_USAGE_RESET = re.compile(r"^(?:your\s+)?(?:claude(?:\.ai)?\s+)?usage limit has reset",
                          re.IGNORECASE)
# Вставка посреди набираемой реплики (AO доставил её, пока Гриша печатал).
# Закрытый тег вырезается, слова по обе стороны склеиваются («если подня» +
# «л»); у незакрытой вставки конца не видно — слово человека всё, что до неё.
_INJECTED_TAGS = ("task-notification", "cross-session-message", "teammate-message",
                  "system-reminder", "ao-session-delivery")
_INJECTED_BLOCK = re.compile(
    r"<({0})\b[^>]*>.*?</\1>".format("|".join(_INJECTED_TAGS)), re.DOTALL)
_INJECTED_INLINE = re.compile(
    r"<(?:{0})\b|\[watch\] |\[alert\b|\[linear [A-Z]+-\d+|\[Cross-session|"
    r"\[SYSTEM NOTIFICATION".format("|".join(_INJECTED_TAGS)))
# Вставка «вставлено из буфера» (SOC-101 F47): харнесс оборачивает длинный текст в
# ``<pasted_content id="…">…</pasted_content id="…">`` — и так же обернул агентскую
# доставку AO (origin.kind human!). Обёртку снимаем, содержимое судим как обычно:
# доставка/межсессионная почта внутри отсекаются, слова Гриши остаются.
_PASTED_TAG = re.compile(r"</?pasted_content\b[^>]*>", re.IGNORECASE)
_ATTACHED_RE = re.compile(r"\s*Attached files \(read these files in the workspace\):.*\Z",
                          re.DOTALL)
_CORRELATION_RE = re.compile(r"[ \t]*\[?AO transcript correlation ID[^\n\]]*\]?", re.IGNORECASE)


def clip(text: str, limit: int = CLIP) -> str:
    flat = " ".join(str(text or "").split())
    if len(flat) <= limit:
        return flat
    return flat[: max(0, limit - 1)].rstrip() + "…"


def log_path(thread_dir: Optional[Path] = None) -> Optional[Path]:
    """Путь к журналу: env, иначе поле ``dialog-log:`` нити; None — не настроен."""
    raw = (os.environ.get(LOG_ENV) or "").strip()
    base: Optional[Path] = None
    if not raw and thread_dir is not None:
        from .stream import passport_path

        raw = (fields.read_field(passport_path(Path(thread_dir)), LOG_FIELD) or "").strip()
        base = paths.find_tide_root(Path(thread_dir))
    if not raw:
        return None
    p = Path(raw).expanduser()
    if not p.is_absolute() and base is not None:
        p = base / p
    return p


def _read_tail(path: Path) -> str:
    with open(path, "rb") as fh:
        fh.seek(0, 2)
        size = fh.tell()
        fh.seek(max(0, size - _TAIL_BYTES))
        return fh.read().decode("utf-8", errors="ignore")


def render_row(row: dict) -> Optional[str]:
    """Одна строка jsonl пульта → ``- ts · кто · канал · текст`` (None — пустая)."""
    text = clip(row.get("text") or "")
    if not text:
        return None
    who = AGENT if row.get("dir") == "out" else HUMAN
    return "- {0} · {1} · {2} · {3}".format(
        row.get("ts") or "?", who, row.get("kind") or "?", text)


def tail(thread_dir: Optional[Path] = None, n: int = 12) -> List[str]:
    """Последние *n* реплик (старые выше): журнал пульта + ``dialog.md`` нити.

    Пульт знает Telegram и Linear, ``dialog.md`` — слова из сессий AO; посеву нужны
    оба. Слиты по времени, одна реплика в обоих (``[tg]`` пишут оба) — один раз.
    [] — ни одного журнала нет/не читается.
    """
    merged = _merge(_log_lines(thread_dir) + _thread_lines(thread_dir))
    return merged[-n:] if n > 0 else merged


def _log_lines(thread_dir: Optional[Path]) -> List[str]:
    """Хвост журнала пульта строками ``- ts · кто · канал · текст`` — только ЭТОЙ нити.

    Журнал из ``$TIDE_DIALOG_LOG`` общий на все проекты (SOC-101 F6: в посев лезли
    пинги чужих сессий): из него берутся только записи, адресованные нити
    (:func:`_row_of_thread`); общий не-jsonl журнал не разобрать — не берётся.
    Журнал из поля ``dialog-log:`` нити — её собственный, берётся целиком.
    """
    path = log_path(thread_dir)
    if path is None or not path.is_file():
        return []
    shared = bool((os.environ.get(LOG_ENV) or "").strip())
    try:
        text = _read_tail(path)
    except OSError:
        return []
    lines = text.splitlines()
    if path.suffix != ".jsonl":
        return [] if shared else [ln.rstrip() for ln in lines if ln.strip()]
    handles = _thread_handles(thread_dir) if shared else set()
    out: List[str] = []
    for raw in lines:
        try:
            row = json.loads(raw)
        except ValueError:
            continue  # the cut first line of the tail, or a torn write
        if not isinstance(row, dict):
            continue
        if shared and not _row_of_thread(row, thread_dir, handles):
            continue
        if row.get("dir") != "out" and is_harness_notice(str(row.get("text") or "")):
            continue  # уведомление харнесса — не реплика Гриши (F17)
        line = render_row(row)
        if line:
            out.append(line)
    return out


def _row_of_thread(row: dict, thread_dir: Optional[Path], handles: "set") -> bool:
    """Запись пульта адресована нити: ``thread``/``route`` (``проект/нить``) называют
    её слаг, или ``ao_session`` — AO-сессия одной из её сессий."""
    if thread_dir is None:
        return False
    tslug = slug.entry_slug(Path(thread_dir).name)
    for key in ("thread", "route"):
        val = str(row.get(key) or "").strip().rstrip("/")
        if val and slug.entry_slug(val.rsplit("/", 1)[-1]) == tslug:
            return True
    ao = str(row.get("ao_session") or "").strip()
    return bool(ao) and ao in handles


def _thread_handles(thread_dir: Optional[Path]) -> "set":
    """AO-хэндлы сессий нити — по реестру терминалов (``arc`` внутри папки нити)."""
    if thread_dir is None:
        return set()
    from .. import registry

    try:
        reg = registry.read(paths.control_home())
    except Exception:  # noqa: BLE001 — нет control-home: хэндлов не знаем
        return set()
    base = str(Path(thread_dir).resolve())
    out = set()
    for rec in reg.values():
        arc = str((rec or {}).get("arc") or "")
        handle = str((rec or {}).get("handle") or "").strip()
        if handle and arc and str(Path(arc).resolve()).startswith(base):
            out.add(handle)
    return out


def _thread_lines(thread_dir: Optional[Path]) -> List[str]:
    """Реплики ``dialog.md`` нити, текст обрезан до :data:`CLIP`."""
    if thread_dir is None:
        return []
    path = dialog_path(Path(thread_dir))
    if path.resolve() == (log_path(thread_dir) or Path()).resolve():
        return []  # журналом назначен сам dialog.md — он уже прочитан
    try:
        text = _read_tail(path)
    except OSError:
        return []
    out: List[str] = []
    for ln in text.splitlines():
        m = _LINE_RE.match(ln)
        if m and m.group(2).strip() == HUMAN and is_harness_notice(m.group(4)):
            continue  # записано до фильтра F17 — при сборке тоже отсекаем
        if m:
            out.append("- {0} · {1} · {2} · {3}".format(
                m.group(1), m.group(2).strip(), m.group(3), clip(m.group(4))))
    return out


def _stamp(raw: str) -> Optional[datetime]:
    """Время строки как локальное наивное (пульт пишет UTC с зоной, dialog.md — местное)."""
    try:
        ts = datetime.fromisoformat(raw.replace("Z", "+00:00"))
    except ValueError:
        return None
    return ts.astimezone().replace(tzinfo=None) if ts.tzinfo else ts


def _merge(lines: List[str]) -> List[str]:
    """Слить по времени; та же реплика того же человека в пределах :data:`DUP_WINDOW` — одна.

    Строки без разбираемого времени остаются впереди в своём порядке."""
    keyed = []
    for i, ln in enumerate(lines):
        m = _LINE_RE.match(ln)
        ts = _stamp(m.group(1)) if m else None
        keyed.append((ts or datetime.min, i, ln, m))
    keyed.sort(key=lambda k: (k[0], k[1]))
    out: List[str] = []
    seen: dict = {}
    for ts, _i, ln, m in keyed:
        if m and ts != datetime.min:
            key = (m.group(2).strip(), " ".join(m.group(4).split()))
            prev = seen.get(key)
            if prev is not None and abs((ts - prev).total_seconds()) <= DUP_WINDOW:
                continue
            seen[key] = ts
        out.append(ln)
    return out


# --- слова человека → <нить>/dialog.md ---------------------------------------

def human_text(prompt: str, origin: object = None) -> Optional[Tuple[str, str]]:
    """Промпт → ``(канал, текст)`` слов человека; None — промпт не его.

    *origin* — ``origin`` из payload хука, если харнесс его дал: всё, что не
    ``{"kind": "human"}``, — не человек. Иначе — по тексту (см.
    :data:`_INJECTED_PREFIXES`). ``[tg]`` в начале — Telegram через пульт.
    """
    if isinstance(origin, dict) and origin.get("kind") not in (None, "human"):
        return None
    text = _CORRELATION_RE.sub("", str(prompt or ""))
    text = _PASTED_TAG.sub("", text)
    text = _ATTACHED_RE.sub("", text).strip()
    if text.startswith(_INJECTED_PREFIXES) or is_harness_notice(text):
        return None
    text = _INJECTED_BLOCK.sub("", text)
    if text.lstrip().startswith(_INJECTED_PREFIXES):
        return None
    m = _INJECTED_INLINE.search(text)
    if m:
        text = text[: m.start()]
    channel = CH_TG if _TG_RE.match(text) else CH_AO
    body = " ".join(_TG_RE.sub("", text).split())
    return (channel, body) if body else None


def is_harness_notice(text: str) -> bool:
    """Уведомление харнесса (лимит, межсессионная почта, системная вставка) — не
    слово человека, где бы в тексте оно ни стояло, если вокруг него нет живых слов.

    Закрытые вставки посреди реплики вырезает :func:`human_text`; тут — тексты,
    которые целиком служебные: «Your claude.ai usage limit has reset…»,
    «[Cross-session idle notice] …», «[SYSTEM NOTIFICATION - NOT USER INPUT] …»."""
    raw = str(text or "")
    flat = " ".join(_PASTED_TAG.sub("", raw).split())
    if not flat:
        # одна обёртка pasted_content без слов — след доставки, записанной до F47
        return bool(_PASTED_TAG.search(raw))
    return flat.startswith(_INJECTED_PREFIXES) or bool(_USAGE_RESET.match(flat))


def dialog_path(thread_dir: Path) -> Path:
    return Path(thread_dir) / DIALOG_FILENAME


def format_line(who: str, channel: str, text: str,
                now: Optional[datetime] = None) -> str:
    stamp = (now or datetime.now()).isoformat(timespec="seconds")
    return "- {0} · {1} · {2} · {3}".format(stamp, who, channel, text)


def append(thread_dir: Path, who: str, channel: str, text: str,
           now: Optional[datetime] = None) -> str:
    """Дописать строку реплики в ``dialog.md`` нити; OSError — наверх."""
    line = format_line(who, channel, " ".join(str(text).split()), now)
    path = dialog_path(thread_dir)
    prefix = "" if path.is_file() else HEADER
    with open(path, "a", encoding="utf-8") as fh:
        fh.write(prefix + line + "\n")
    return line


def log_human(root: Path, thread_dir: Optional[Path], prompt: str, *,
              origin: object = None, source: str = "",
              now: Optional[datetime] = None) -> Optional[str]:
    """Слова человека из промпта → ``dialog.md`` нити; вернуть строку (None — не его).

    *thread_dir* None — сессия не нашлась в нити: реплика теряется, это сбой.
    Сбой (и OSError записи) не роняет промпт, но и не молчит: :func:`report_failure`.
    """
    said = human_text(prompt, origin)
    if said is None:
        return None
    channel, body = said
    if thread_dir is None:
        report_failure(root, "сессия {0} не найдена ни в одной нити — реплика не записана: {1}"
                       .format(source or "?", clip(body, 200)), source=source)
        return None
    try:
        return append(thread_dir, HUMAN, channel, body, now)
    except OSError as exc:
        report_failure(root, "запись {0} упала ({1}) — реплика не записана: {2}"
                       .format(dialog_path(thread_dir), exc, clip(body, 200)), source=source)
        return None


def report_failure(root: Optional[Path], detail: str, *, source: str = "") -> None:
    """Сбой журнала: stderr + ``.tide/state/dialog-errors.log`` + ``$TIDE_ALERT_CMD``.

    Сигнал уходит менеджеру (``TIDE_ALERT_ROUTE=manager``), пульт гасит повторы.
    Сам никогда не падает — промпт важнее сигнала.
    """
    text = "tide: журнал диалога: " + detail
    print(text, file=sys.stderr)
    if root is not None:
        try:
            log = paths.state_dir(Path(root)) / ERRORS_LOG
            log.parent.mkdir(parents=True, exist_ok=True)
            with open(log, "a", encoding="utf-8") as fh:
                fh.write("{0} {1}\n".format(datetime.now().isoformat(timespec="seconds"), text))
        except OSError:
            pass
    cmd = (os.environ.get(ALERT_CMD_ENV) or "").strip()
    if not cmd:
        return
    env = dict(os.environ, TIDE_ALERT_TEXT=text, TIDE_ALERT_ROUTE="manager",
               TIDE_ALERT_SOURCE=source)
    try:
        subprocess.run(shlex.split(cmd) + [text], env=env, timeout=30,
                       capture_output=True, text=True)
    except (OSError, ValueError, subprocess.SubprocessError):
        pass


